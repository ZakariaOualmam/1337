#include <unistd.h>

int	main(int ac, char **av)
{
	int	j;
	int	g;

	g = ac -1;
	while (g != 0)
	{
		j = 0;
		while (av[g][j])
		{
			write (1, &av[g][j], 1);
			j++;
		}
		write (1, "\n", 1);
		g--;
	}
	return (0);
}
